import { beforeEach, describe, expect, it, vi } from "vitest";
import type { AxiosResponse } from "axios";

import { httpClient } from "@/shared/lib/httpClient";
import { getWeeklyAgenda } from "@/modules/tutor/weekly-schedule/api/weekly-agenda.api";
import { buildNextSessionInfo } from "@/modules/tutor/weekly-schedule/utils/weeklyAgendaNextSession.utils";
import type { BackendWeeklyScheduleResponse } from "@/modules/tutor/weekly-schedule/interfaces/responses/weekly-agenda-backend.interface";
import type { BookedSessionResponse } from "@/modules/tutor/weekly-schedule/interfaces/responses/weekly-agenda.interface";

vi.mock("@/shared/lib/httpClient", () => ({
  httpClient: { get: vi.fn() },
}));

const mockedGet = vi.mocked(httpClient.get);

function buildBackendResponse(
  overrides: Partial<BackendWeeklyScheduleResponse> = {}
): BackendWeeklyScheduleResponse {
  return {
    from: "2026-11-02",
    to: "2026-11-08",
    availabilityBlocks: [
      {
        availabilityBlockId: "b-1",
        date: "2026-11-02",
        startTime: "09:00",
        endTime: "11:00",
        repeatWeekly: false,
        autoGenerated: false,
      },
    ],
    bookings: [
      {
        bookingId: "s-1",
        sessionDate: "2026-11-03",
        startTime: "10:00:00",
        endTime: "11:00:00",
        modality: "VIRTUAL",
        tutorSubjectName: "Física 1",
        studentFullName: "Lucía Pérez",
      },
    ],
    summary: {
      confirmedBookingsCount: 1,
      freeBlocksCount: 2,
      nextClass: {
        bookingId: "s-1",
        sessionDate: "2026-11-03",
        startTime: "10:00:00",
        endTime: "11:00:00",
      },
    },
    ...overrides,
  };
}

const bookedSessions: BookedSessionResponse[] = [
  {
    id: "s-1",
    subjectName: "Física 1",
    studentName: "Lucía Pérez",
    date: "2026-11-03",
    startTime: "10:00:00",
    endTime: "11:00:00",
    modality: "VIRTUAL",
  },
];

describe("agenda semanal - resumen del backend", () => {
  beforeEach(() => {
    mockedGet.mockReset();
  });

  it("mapea los contadores del summary y la próxima clase", async () => {
    const payload = buildBackendResponse();
    mockedGet.mockResolvedValue({
      data: payload,
    } as AxiosResponse<BackendWeeklyScheduleResponse>);

    const agenda = await getWeeklyAgenda("2026-11-02", "2026-11-08");

    expect(agenda.summary).toEqual({
      confirmedBookingsCount: 1,
      freeBlocksCount: 2,
      nextClass: {
        bookingId: "s-1",
        date: "2026-11-03",
        startTime: "10:00:00",
        endTime: "11:00:00",
      },
    });
    expect(agenda.bookedSessions[0]).toMatchObject({ id: "s-1", subjectName: "Física 1" });
  });

  it("mantiene nextClass en null cuando la semana no tiene clases futuras", async () => {
    const payload = buildBackendResponse({
      bookings: [],
      summary: { confirmedBookingsCount: 0, freeBlocksCount: 1, nextClass: null },
    });
    mockedGet.mockResolvedValue({
      data: payload,
    } as AxiosResponse<BackendWeeklyScheduleResponse>);

    const agenda = await getWeeklyAgenda("2026-11-02", "2026-11-08");

    expect(agenda.summary.nextClass).toBeNull();
    expect(agenda.summary.freeBlocksCount).toBe(1);
    expect(agenda.bookedSessions).toEqual([]);
  });
});

describe("buildNextSessionInfo", () => {
  it("enriquece la próxima clase del backend con la materia de la reserva", () => {
    const now = new Date(2026, 10, 2, 9, 0, 0);

    expect(
      buildNextSessionInfo(
        {
          bookingId: "s-1",
          date: "2026-11-03",
          startTime: "10:00:00",
          endTime: "11:00:00",
        },
        bookedSessions,
        now
      )
    ).toEqual({
      subjectName: "Física 1",
      dateLabel: "Mañana",
      timeLabel: "10:00",
    });
  });

  it("devuelve null cuando el backend no informa próxima clase", () => {
    expect(buildNextSessionInfo(null, bookedSessions)).toBeNull();
  });
});
